#!/usr/bin/env node
/**
 * Daily Security Digest - Discord Automation
 * Runs the digest and posts results to Discord
 */

const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const DIGEST_DIR = path.join(__dirname, 'apps', 'daily-security-digest');
const OUTPUT_FILE = path.join(DIGEST_DIR, 'daily-digest.json');

async function runDigest() {
    console.log('🔒 Running Daily Security Digest...');
    
    // Run the digest with JSON output
    execSync('node index.js --json', { 
        cwd: DIGEST_DIR,
        stdio: 'inherit'
    });
    
    // Read the output
    const data = JSON.parse(fs.readFileSync(OUTPUT_FILE, 'utf8'));
    
    // Format for Discord
    let message = '**🔒 DAILY SECURITY DIGEST**\n';
    message += `📅 ${data.date}\n`;
    message += `📊 Found ${data.summary.total} articles across ${data.summary.categories} categories\n\n`;
    
    data.categories.forEach(cat => {
        if (cat.results.length > 0) {
            message += `**${cat.category}**\n`;
            cat.results.slice(0, 2).forEach((r, i) => {
                message += `${i+1}. ${r.title}\n`;
                message += `   ${r.url || ''}\n`;
            });
            message += '\n';
        }
    });
    
    message += `---\n`;
    message += `🤖 Generated by Night Coder`;
    
    return message;
}

runDigest().then(msg => {
    console.log('\n📝 Formatted message ready for Discord:');
    console.log(msg);
}).catch(err => {
    console.error('Error:', err.message);
    process.exit(1);
});
